"""Certificate authority for the agent module (no Qt).

The main harness is its own certificate authority. It signs the server
certificate it presents to agents and the client certificates it issues to them
during enrollment. Agents pin this CA and trust nothing else, so a valid
certificate from a public CA does not let anyone impersonate the main harness.

All key material is produced here with the `cryptography` library, never by a
model: the agent installer is a template the main harness fills with PEM strings
generated by these functions.

Keys are EC P-256 (SECP256R1): modern, small, universally supported by the
Python ``ssl`` stack and TLS 1.3. Private keys are returned as unencrypted PKCS8
PEM; protect them with file permissions where they are stored (the CA key lives
in ``data/agent/``, which is in ``.gitignore``).

Every function takes and returns PEM ``bytes`` so callers can store the material
without knowing the object model. Validity is bounded in days from "now" in UTC.
"""
from __future__ import annotations

import datetime
import hashlib
import ipaddress

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

# Default lifetimes. The CA is long-lived; leaf certificates are short enough
# that a lost one ages out, but the registry (Phase 1) is the real revocation.
CA_DAYS = 3650          # ~10 years
SERVER_DAYS = 825       # server certificate the main harness presents
CLIENT_DAYS = 90        # per-agent client certificate; regenerate the agent after

CA_COMMON_NAME = "SaiHarness Agent CA"
_CURVE = ec.SECP256R1()
_HASH = hashes.SHA256()


# --- serialization helpers -------------------------------------------------

def _key_to_pem(key: ec.EllipticCurvePrivateKey) -> bytes:
    return key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )


def _cert_to_pem(cert: x509.Certificate) -> bytes:
    return cert.public_bytes(serialization.Encoding.PEM)


def load_private_key(key_pem: bytes) -> ec.EllipticCurvePrivateKey:
    key = serialization.load_pem_private_key(key_pem, password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey):
        raise ValueError("not an EC private key")
    return key


def load_certificate(cert_pem: bytes) -> x509.Certificate:
    return x509.load_pem_x509_certificate(cert_pem)


def load_csr(csr_pem: bytes) -> x509.CertificateSigningRequest:
    return x509.load_pem_x509_csr(csr_pem)


def _now() -> datetime.datetime:
    return datetime.datetime.now(datetime.timezone.utc)


def _san_entry(host: str) -> x509.GeneralName:
    """A SAN entry for a host that may be an IP address or a DNS name."""
    try:
        return x509.IPAddress(ipaddress.ip_address(host))
    except ValueError:
        return x509.DNSName(host)


# --- certificate authority -------------------------------------------------

def generate_ca(common_name: str = CA_COMMON_NAME, days: int = CA_DAYS) -> tuple[bytes, bytes]:
    """Create a self-signed CA. Returns ``(key_pem, cert_pem)``.

    The private key is the single most sensitive secret in the whole module.
    """
    key = ec.generate_private_key(_CURVE)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, common_name)])
    now = _now()
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=1))  # tolerate small clock skew
        .not_valid_after(now + datetime.timedelta(days=days))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True, key_cert_sign=True, crl_sign=True,
                content_commitment=False, key_encipherment=False, data_encipherment=False,
                key_agreement=False, encipher_only=False, decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False)
        .sign(key, _HASH)
    )
    return _key_to_pem(key), _cert_to_pem(cert)


def generate_server_cert(
    ca_key_pem: bytes, ca_cert_pem: bytes, host: str, days: int = SERVER_DAYS
) -> tuple[bytes, bytes]:
    """Issue the server certificate the main harness presents to agents.

    ``host`` is what agents connect to (an IP or DNS name); it goes into the SAN
    so the agent's TLS verification accepts it. Returns ``(key_pem, cert_pem)``.
    """
    ca_key = load_private_key(ca_key_pem)
    ca_cert = load_certificate(ca_cert_pem)
    key = ec.generate_private_key(_CURVE)
    now = _now()
    cert = (
        x509.CertificateBuilder()
        .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, host)]))
        .issuer_name(ca_cert.subject)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=1))
        .not_valid_after(now + datetime.timedelta(days=days))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(x509.SubjectAlternativeName([_san_entry(host)]), critical=False)
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False
        )
        .sign(ca_key, _HASH)
    )
    return _key_to_pem(key), _cert_to_pem(cert)


def generate_csr(common_name: str) -> tuple[bytes, bytes]:
    """Generate a fresh key pair and a CSR for it. Runs on the host (the agent).

    Returns ``(key_pem, csr_pem)``. The private key never leaves the host; only
    the CSR is sent to the main harness to be signed.
    """
    key = ec.generate_private_key(_CURVE)
    csr = (
        x509.CertificateSigningRequestBuilder()
        .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, common_name)]))
        .sign(key, _HASH)
    )
    return _key_to_pem(key), csr.public_bytes(serialization.Encoding.PEM)


def sign_csr(
    ca_key_pem: bytes, ca_cert_pem: bytes, csr_pem: bytes, days: int = CLIENT_DAYS
) -> bytes:
    """Sign a client CSR with the CA, producing a client (``clientAuth``) cert.

    Raises ``ValueError`` if the CSR's own signature does not verify. Returns the
    issued certificate as PEM ``bytes``.
    """
    ca_key = load_private_key(ca_key_pem)
    ca_cert = load_certificate(ca_cert_pem)
    csr = load_csr(csr_pem)
    if not csr.is_signature_valid:
        raise ValueError("CSR signature is not valid")
    now = _now()
    cert = (
        x509.CertificateBuilder()
        .subject_name(csr.subject)
        .issuer_name(ca_cert.subject)
        .public_key(csr.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=1))
        .not_valid_after(now + datetime.timedelta(days=days))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.CLIENT_AUTH]), critical=False
        )
        .sign(ca_key, _HASH)
    )
    return _cert_to_pem(cert)


# --- fingerprints and verification ----------------------------------------

def fingerprint(cert_pem: bytes) -> str:
    """Lowercase hex SHA-256 of the DER certificate. The registry key for an agent."""
    return load_certificate(cert_pem).fingerprint(_HASH).hex()


def fingerprint_der(der: bytes) -> str:
    """Same fingerprint computed from a DER certificate, as the TLS handshake hands it
    to the server. Equals ``fingerprint`` of the PEM form of the same certificate."""
    return hashlib.sha256(der).hexdigest()


def verify_signed_by_ca(cert_pem: bytes, ca_cert_pem: bytes) -> bool:
    """True if ``cert_pem`` was signed by the CA's private key. No chain/time checks.

    This is the cryptographic half of the mTLS admission check; the registry adds
    the fingerprint-allowlist and status checks on top (Phase 1).
    """
    try:
        cert = load_certificate(cert_pem)
        ca_pub = load_certificate(ca_cert_pem).public_key()
        if not isinstance(ca_pub, ec.EllipticCurvePublicKey):
            return False
        ca_pub.verify(
            cert.signature,
            cert.tbs_certificate_bytes,
            ec.ECDSA(cert.signature_hash_algorithm),
        )
        return True
    except Exception:
        return False
